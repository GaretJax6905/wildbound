const ALIAS = { '’': "'", '‘': "'", '“': '"', '”': '"', '—': '-', '–': '-', 'é': 'e', '×': 'x', '→': '>', '←': '<' };

function glyph(ch) {
  if (ch === '‌') return null;
  return G[ch] || G[ALIAS[ch]] || G['?'];
}

// scale: 1 = normal text, 2 = big headings
export function pxWidth(str, scale = 1) {
  let w = 0;
  for (const ch of String(str).replace(/…/g, '...')) {
    const gl = glyph(ch);
    if (gl) w += (gl[0].length + 1) * scale;
  }
  return Math.max(0, w - scale);
}

export function pxText(g, str, x, y, col, shadow, scale = 1, align = 'left') {
  const s = String(str).replace(/…/g, '...');
  let cx = Math.round(align === 'center' ? x - pxWidth(s, scale) / 2 : align === 'right' ? x - pxWidth(s, scale) : x);
  const cy = Math.round(y);
  const pass = (color, ox, oy) => {
    g.fillStyle = color;
    let xx = cx;
    for (const ch of s) {
      const gl = glyph(ch);
      if (!gl) continue;
      for (let r = 0; r < gl.length; r++) {
        const row = gl[r];
        for (let c = 0; c < row.length; c++) if (row[c] === '1') g.fillRect(xx + c * scale + ox, cy + r * scale + oy, scale, scale);
      }
      xx += (gl[0].length + 1) * scale;
    }
  };
  if (shadow) pass(shadow, scale, scale);
  pass(col, 0, 0);
}
